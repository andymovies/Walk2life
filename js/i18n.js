let idioma = 'es';
try {
  const guardado = localStorage.getItem('idioma');
  const nav = (navigator.language || 'es').slice(0, 2);
  idioma = guardado || (UI[nav] ? nav : 'es');
} catch {}

export const getIdioma = () => idioma;
export function setIdioma(i) {
  idioma = i;
  try { localStorage.setItem('idioma', i); } catch {}
}

// Texto de interfaz. Los idiomas sin traducir (fr, it) caen al inglés y luego al español.
export function t(clave, vars = {}) {
  let s = (UI[idioma] && UI[idioma][clave]) || (idioma !== 'es' && UI.en[clave]) || UI.es[clave] || clave;
  for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}

// Texto de contenido: acepta cadena u objeto por idioma.
export function tx(v) {
  if (v == null) return '';
  if (typeof v === 'string') return v;
  return v[idioma] || v.es || Object.values(v)[0] || '';
}
